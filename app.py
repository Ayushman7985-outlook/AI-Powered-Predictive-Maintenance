import json
import joblib
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt
from sklearn.metrics import ConfusionMatrixDisplay, confusion_matrix
from src.config import MODEL_PATH, METRICS_PATH, FEATURES, OUTPUT_DIR
from src.data_loader import load_data
from src.predict import predict_machine

st.set_page_config(page_title="AI Predictive Maintenance", page_icon="🛠️", layout="wide")
st.title("🛠️ AI-Powered Predictive Maintenance for IoT Devices")
st.caption("Demo using historical or simulated machine-condition data — not connected to physical sensors.")

df, source = load_data()
st.sidebar.header("Data and model")
st.sidebar.write(f"**Dataset source:** {source}")
st.sidebar.write(f"**Records:** {len(df):,}")
if not MODEL_PATH.exists():
    st.warning("Model is not trained yet. In the project folder, run `python -m src.train`, then refresh this page.")
    st.stop()

bundle = joblib.load(MODEL_PATH)
model = bundle["model"]
st.sidebar.success("Trained model loaded")

if METRICS_PATH.exists():
    metrics = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
    st.subheader("Model evaluation")
    cols = st.columns(4)
    for col, label, key in zip(cols, ["Accuracy", "Precision", "Recall", "F1 score"],
                               ["accuracy", "precision", "recall", "f1_score"]):
        col.metric(label, f"{metrics.get(key, 0):.1%}")
    st.caption("Metrics are calculated on a held-out test split. For rare failures, recall and precision are important alongside accuracy.")

tab1, tab2, tab3 = st.tabs(["🔎 Predict machine risk", "📊 Dataset overview", "📈 Model evidence"])
with tab1:
    st.subheader("Enter machine operating conditions")
    c1, c2, c3 = st.columns(3)
    with c1:
        machine_type = st.selectbox("Machine type", ["L", "M", "H"], help="AI4I dataset product quality type.")
        air = st.number_input("Air temperature (K)", min_value=290.0, max_value=310.0, value=300.0, step=0.5)
    with c2:
        process = st.number_input("Process temperature (K)", min_value=300.0, max_value=320.0, value=310.0, step=0.5)
        rpm = st.number_input("Rotational speed (rpm)", min_value=800, max_value=3000, value=1500, step=50)
    with c3:
        torque = st.number_input("Torque (Nm)", min_value=1.0, max_value=80.0, value=40.0, step=1.0)
        wear = st.number_input("Tool wear (min)", min_value=0, max_value=300, value=100, step=5)
    if st.button("Predict machine condition", type="primary"):
        result = predict_machine({
            "Type": machine_type, "Air temperature [K]": air,
            "Process temperature [K]": process, "Rotational speed [rpm]": rpm,
            "Torque [Nm]": torque, "Tool wear [min]": wear,
        })
        st.metric("Estimated failure risk", f"{result['risk_percent']:.2f}%")
        if result["prediction"] == 1:
            st.error("⚠️ Model flags potential failure risk. Inspect the machine; this is a model estimate, not a safety guarantee.")
        else:
            st.success("✅ Model does not flag a failure for these inputs.")
        st.write(f"**Prediction:** {result['status']}")
        st.caption(f"Training data source: {result['data_source']}")

with tab2:
    st.subheader("Dataset preview")
    st.dataframe(df.head(20), use_container_width=True)
    left, right = st.columns(2)
    with left:
        counts = df["Machine failure"].value_counts().sort_index()
        fig, ax = plt.subplots()
        ax.bar(["No failure (0)", "Failure (1)"], [counts.get(0, 0), counts.get(1, 0)])
        ax.set_ylabel("Record count")
        ax.set_title("Failure label distribution")
        st.pyplot(fig)
        plt.close(fig)
    with right:
        st.write("**Summary statistics**")
        st.dataframe(df.select_dtypes(include="number").describe().T, use_container_width=True)

with tab3:
    st.subheader("Confusion matrix")
    plot_path = OUTPUT_DIR / "confusion_matrix.png"
    if plot_path.exists():
        st.image(str(plot_path), caption="Generated by `python -m src.evaluate`")
    else:
        st.info("Run `python -m src.evaluate` to generate the confusion matrix and classification report.")
    report_path = OUTPUT_DIR / "classification_report.txt"
    if report_path.exists():
        st.text(report_path.read_text(encoding="utf-8"))
    st.write("**Interpretation:** False negatives are failures the model misses. False positives are warnings when the machine does not fail. In maintenance, missed failures can be costly, so evaluate recall as well as precision.")
